-- =====================================================
-- [Part 3-1] Basic JOINs (Legacy Syntax)
-- 내용: CROSS, EQUI, NON-EQUI, SELF JOIN (WHERE 절 사용 방식)
-- =====================================================

-- -----------------------------------------------------
-- 1. CROSS JOIN (카테시안 곱)
-- -----------------------------------------------------
-- 설명: 조인 조건 없이 두 테이블의 모든 행을 단순히 곱하여 결합합니다.
-- 결과: 데이터가 방대해져 시스템에 부하를 줄 수 있으므로 주의해야 합니다.
SELECT * FROM emp, dept;

-- -----------------------------------------------------
-- 2. EQUI JOIN (등가 조인)
-- -----------------------------------------------------
-- 설명: 두 테이블에 공통으로 존재하는 컬럼을 '=' 연산자로 연결합니다.
-- 주의: 컬럼명이 같을 경우(deptno) 반드시 '테이블명.컬럼명'으로 명시해야 합니다.
SELECT ename, dname
FROM emp, dept
WHERE emp.deptno = dept.deptno AND ename = 'MILLER';

-- -----------------------------------------------------
-- 3. NON-EQUI JOIN (비등가 조인)
-- -----------------------------------------------------
-- 설명: '=' 연산자가 아닌 범위 연산자(BETWEEN 등)를 사용하여 조인합니다.
-- 예제: 사원의 급여가 등급표(salgrade)의 최저~최고 범위 내에 있는지 확인합니다.
SELECT ename, sal, grade
FROM emp, salgrade
WHERE emp.sal BETWEEN losal AND hisal;

-- -----------------------------------------------------
-- 4. SELF JOIN (자체 조인)
-- -----------------------------------------------------
-- 설명: 하나의 테이블을 마치 두 개의 테이블인 것처럼 별칭(Alias)을 주어 조인합니다.
-- 예제: 사원(e1) 테이블과 관리자(e2) 테이블로 나누어 사원의 매니저 이름을 찾습니다.
SELECT e1.ename AS 사원, e2.ename AS 관리자
FROM emp e1, emp e2
WHERE e1.mgr = e2.empno;
