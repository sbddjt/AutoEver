/* ====================================================
   [DB] 7장 DML - 데이터 수정 및 삭제 (UPDATE / DELETE)
   주의: WHERE 절을 생략하면 테이블 전체에 영향을 미침
   ==================================================== */

-- [UPDATE] 데이터 수정 ---------------------------------

-- 1. 특정 데이터 수정
-- 조건: DEPTNO가 10인 행만 수정
-- 변경: LOC -> '제주', DNAME -> '비서실'
UPDATE DEPT1
SET LOC = '제주', 
    DNAME = '비서실'
WHERE DEPTNO = 10;

/* ⚠️ 주의: WHERE 절 생략 시
UPDATE DEPT1 SET LOC = '제주'; 
-> 모든 부서의 위치가 '제주'로 바뀜 (주의 요망)
*/


-- [DELETE] 데이터 삭제 ---------------------------------

-- 1. 특정 데이터 삭제
-- 조건: DEPTNO가 10인 행만 삭제
DELETE FROM DEPT 
WHERE DEPTNO = 10;

-- 2. 모든 데이터 삭제
-- WHERE 절이 없으므로 테이블 내 모든 행이 삭제됨
-- (테이블 구조는 남음)
DELETE FROM DEPT;
