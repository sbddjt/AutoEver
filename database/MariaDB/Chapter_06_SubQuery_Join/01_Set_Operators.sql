-- =====================================================
-- [Part 1] SET OPERATOR (집합 연산자)
-- 내용: UNION, UNION ALL, INTERSECT, EXCEPT 실습
-- 전제: EMP 테이블(부서 10, 20, 30), DEPT 테이블(부서 10, 20, 30, 40)
-- =====================================================

-- -----------------------------------------------------
-- 1. UNION (합집합 - 중복 제거)
-- -----------------------------------------------------
-- 설명: 두 테이블의 DEPTNO를 합치되, 중복되는 값은 한 번만 출력합니다.
-- 참고: DISTINCT를 명시하지 않아도 기본적으로 중복이 제거됩니다.
SELECT DEPTNO 
FROM EMP
UNION
SELECT DEPTNO 
FROM DEPT;
-- 예상 결과: 10, 20, 30, 40

-- -----------------------------------------------------
-- 2. UNION ALL (합집합 - 중복 포함)
-- -----------------------------------------------------
-- 설명: 두 테이블의 데이터를 단순하게 합쳐서 모두 출력합니다.
-- 특징: 중복 제거 연산을 하지 않으므로 UNION보다 속도가 빠릅니다.
SELECT DEPTNO 
FROM EMP
UNION ALL
SELECT DEPTNO 
FROM DEPT;
-- 예상 결과: 10, 20, 30, 10, 20, 30, 40 (EMP의 데이터 + DEPT의 데이터)

-- -----------------------------------------------------
-- 3. INTERSECT (교집합)
-- -----------------------------------------------------
-- 설명: 두 테이블에 공통적으로 존재하는 데이터만 추출합니다.
SELECT DEPTNO 
FROM EMP
INTERSECT
SELECT DEPTNO 
FROM DEPT;
-- 예상 결과: 10, 20, 30 (양쪽에 모두 있는 값)

-- -----------------------------------------------------
-- 4. EXCEPT (차집합)
-- -----------------------------------------------------
-- Case 1: EMP에는 있고 DEPT에는 없는 데이터 조회
-- 결과: EMP의 모든 부서(10, 20, 30)는 DEPT에도 존재하므로 결과가 없습니다.
SELECT DEPTNO 
FROM EMP 
EXCEPT 
SELECT DEPTNO 
FROM DEPT;

-- Case 2: DEPT에는 있고 EMP에는 없는 데이터 조회
-- 결과: DEPT의 40번 부서는 EMP에 없으므로 40이 출력됩니다.
SELECT DEPTNO 
FROM DEPT 
EXCEPT 
SELECT DEPTNO 
FROM EMP;
