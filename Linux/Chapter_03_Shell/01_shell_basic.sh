#!/bin/bash

# ==========================================
# 1. 쉘(Shell) 확인 및 변경
# ==========================================

# 1-1. 시스템이 지원하는 쉘 목록 확인
cat /etc/shells

# 1-2. 현재 사용자의 로그인 쉘 확인 (/etc/passwd)
# 사용법: grep [계정이름] /etc/passwd
grep seongyun /etc/passwd

# 1-3. 쉘 변경 (chsh) - 영구 변경 (재로그인 필요)
# -s : 지정하는 쉘로 변경 (반드시 절대 경로 사용)
# chsh -s /bin/csh seongyun  # csh로 변경
# chsh -s /bin/bash seongyun # bash로 복구 (기본)

# 1-4. 일회성 쉘 변경 (Sub Shell)
# 터미널에서 'sh' 또는 'csh' 입력 시 임시 변경, 'exit'로 복귀


# ==========================================
# 2. 내장 명령 vs 외부 명령 출력
# ==========================================

# 2-1. echo: 문자열 출력
echo -n "줄바꿈 없이 출력됩니다."
echo " 줄바꿈 포함"

# 2-2. printf: C언어 스타일 서식 출력
printf "linux\n"                 # 줄바꿈 포함 (\n)
printf "%d + %d = %d\n" 1 3 4    # 서식 지정 (1 + 3 = 4)
